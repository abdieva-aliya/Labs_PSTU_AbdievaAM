#include <iostream>
#include <clocale>
#include <string>
using namespace std;

// Функция извлечения слова
string ex_word(char a[10][60], int& i, int& j) {
    string w = "";
    
    // Идем по строке, пока не встретим '0' или конец строки
    while (a[i][j] != '0' && a[i][j] != '\0') {
        w += a[i][j];
        j++;
    }
    
    // Пропускаем '0'
    if (a[i][j] == '0') {
        j++;
    }
    
    return w;
}

int main() {
    setlocale(LC_ALL, ".65001");
    char a[10][60];
    int n;

    cout << "Введите количество строк: ";
    cin >> n;

    cout << "Введите строки с цифрами:" << endl;
    for (int i = 0; i < n; i++) {
        cin >> a[i];
    }

    cout << "Результат:" << endl;

    string new_l = "("; // Текущая строка для вывода
    int len = 1;        // Длина текущей строки

    // Проходим по всем введенным строкам
    for (int i = 0; i < n; i++) {
        int j = 0; // Сбрасываем столбец для каждой новой строки
        
        while (a[i][j] != '\0') {
            
            // Если встретили '0', просто переступаем
            if (a[i][j] == '0') {
                j++;
            } 
            else {
                // Иначе вызываем функцию и достаем слово
                string w = ex_word(a, i, j);
                
                // Считаем, сколько места займет: слово + запятая (если это не первое слово)
                int x = w.length();
                if (new_l != "(") {
                    x = x + 1; // +1 для запятой
                }

                // Если слово не влезает в 60 символов
                if (len + x + 1 > 60) {
                    cout << new_l << ")" << endl; // Выводим старую строку
                    
                    // Начинаем новую
                    new_l = "(" + w; 
                    len = 1 + w.length();
                } else {
                    // Если влезает, добавляем
                    if (new_l != "(") {
                        new_l += ",";
                    }
                    new_l += w;
                    len += x;
                }
            }
        }
    }

    // Выводим последнюю строку, если она не пустая
    if (new_l != "(") {
        cout << new_l << ")" << endl;
    }
    return 0;
}
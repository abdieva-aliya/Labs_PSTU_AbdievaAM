#include <iostream>
#include <clocale>
#include <string>
using namespace std;

// Функция извлечения одного слова из массива.
// i и j передаются по ссылке, чтобы сдвигать позицию чтения.
string ex_word(char a[10][60], int& i, int& j) {
    string w = "";
    
    // Читаем цифры, пока не встретим '0' или конец строки
    while (a[i][j] != '0' && a[i][j] != '\0') {
        w += a[i][j];
        j++;
    }
    
    // Пропускаем разделитель '0'
    if (a[i][j] == '0') {
        j++;
    }
    
    return w;
}

int main() {
    setlocale(LC_ALL, ".65001");
    
    char a[10][60]; // Двумерный массив (10 строк по 60 символов)
    int n;          // Количество строк для ввода

    cout << "Введите количество строк: ";
    cin >> n;

    cout << "Введите строки с цифрами:" << endl;
    for (int i = 0; i < n; i++) {
        cin >> a[i]; // Ввод строк в массив
    }

    cout << "Результат:" << endl;

    string new_l = "("; // Буфер текущей строки (начинаем со скобки)
    int len = 1;        // Текущая длина строки (1 символ — скобка)

    // Перебираем все введенные строки массива
    for (int i = 0; i < n; i++) {
        int j = 0; // Индекс символа в текущей строке
        
        while (a[i][j] != '\0') {
            
            // Если это '0', просто пропускаем его
            if (a[i][j] == '0') {
                j++;
            } 
            else {
                // Если цифра — извлекаем слово
                string w = ex_word(a, i, j);
                
                // Считаем длину добавки: слово + запятая (если строка не пустая)
                int x = w.length();
                if (new_l != "(") {
                    x = x + 1; // +1 для запятой
                }

                // Проверяем лимит: текущая длина + добавка + 1 (под скобку) > 60
                if (len + x + 1 > 60) {
                    // Не влезает — выводим строку и начинаем новую
                    cout << new_l << ")" << endl; 
                    new_l = "(" + w; 
                    len = 1 + w.length();
                } else {
                    // Влезает — добавляем через запятую (если нужно)
                    if (new_l != "(") {
                        new_l += ",";
                    }
                    new_l += w;
                    len += x;
                }
            }
        }
    }

    // Выводим последнюю оставшуюся строку
    if (new_l != "(") {
        cout << new_l << ")" << endl;
    }
    return 0;
}